"""Regenerate app/startup/crt0.S from hard evidence:
   - reference/bootloader_0x08000000_8k.bin   (immutable vector table -> slot map)
   - reference/2429-H1N4JPF20A-220524.app.bin (stock veneer targets / trap codes)
   - SDK n32l40x.h IRQn_Type                  (official peripheral names)
"""
import struct, re, sys, os

B = chr(92)
SDK = sys.argv[1]

# ---------- official N32L40x IRQ names ----------
hdr = open(os.path.join(SDK, 'firmware/CMSIS/device/n32l40x.h'), encoding='utf-8',
           errors='replace').read()
blk = re.search(r'typedef enum IRQn.*?\}\s*IRQn_Type', hdr, re.S).group(0)
irqname = {}
for m in re.finditer(r'^\s*(\w+)_IRQn\s*=\s*(-?\d+)', blk, re.M):
    irqname[int(m.group(2))] = m.group(1)

# ---------- bootloader vector table -> slot map ----------
boot = open('reference/bootloader_0x08000000_8k.bin', 'rb').read()
core = {2: 'NMI', 3: 'HardFault', 4: 'MemManage', 5: 'BusFault', 6: 'UsageFault',
        11: 'SVCall', 12: 'DebugMon', 14: 'PendSV', 15: 'SysTick'}
slot_src = {}
for i in range(256):
    w, = struct.unpack_from('<I', boot, i * 4)
    t = w & ~1
    if 0x0800202a <= t <= 0x08002201 and (t - 0x0800202a) % 8 == 0:
        s = (t - 0x0800202a) // 8
        slot_src[s] = core[i] if i in core else irqname.get(i - 16, 'IRQ%d' % (i - 16))

# ---------- stock veneer targets / trap codes ----------
app = open('reference/2429-H1N4JPF20A-220524.app.bin', 'rb').read()
def rd16(a): return struct.unpack_from('<H', app, a - 0x08002000)[0]
def bl_target(a):
    hi, lo = rd16(a), rd16(a + 2)
    imm = ((hi & 0x7FF) << 12) | ((lo & 0x7FF) << 1)
    s = (hi >> 10) & 1
    j1, j2 = (lo >> 13) & 1, (lo >> 11) & 1
    imm |= ((~(j1 ^ s)) & 1) << 23 | ((~(j2 ^ s)) & 1) << 22 | s << 24
    if s: imm -= 1 << 25
    return a + 4 + imm

TRAPFN = 0x08002e64
trap, empty, real = {}, set(), {}
for s in range(59):
    tgt = bl_target(0x0800202a + 8 * s + 2)
    w0 = rd16(tgt)
    if (w0 & 0xFF00) == 0x2000 and bl_target(tgt + 2) == TRAPFN:      # movs r0,#c ; bl trap
        trap[s] = w0 & 0xFF
    elif w0 == 0x4770:                                                # bx lr
        empty.add(s)
    else:
        real[s] = tgt

# handler symbol per slot
def sym(s):
    src = slot_src.get(s)
    if src is None:
        return 'Slot%d_Unused_Handler' % s
    return src + '_Handler' if src in core.values() else src + '_IRQHandler'

L = []
A = L.append
A('''/* ============================================================================
 * app/startup/crt0.S  --  fixed preamble for the Hiworld canbox APP
 * Nations N32L406CBL7 (Cortex-M4F, Thumb-2).
 *
 * GENERATED by scratch gen_crt0.py from three pieces of hard evidence:
 *   reference/bootloader_0x08000000_8k.bin    immutable vector table -> slot map
 *   reference/2429-H1N4JPF20A-220524.app.bin  stock veneer targets + trap codes
 *   Nations N32L40x_Library 2.3.0 n32l40x.h   official IRQn_Type names
 *
 * This file owns flash 0x08002000..0x08002209 and MUST keep that exact layout:
 *
 *   0x08002000..0x08002029   42 bytes, NOT dispatched to -> safe filler
 *   0x0800202a..0x08002201   59 x 8-byte veneers (push {r4,lr}; bl h; pop {r4,pc})
 *   0x08002202..0x08002209   app entry veneer  <-- bootloader does `bl 0x08002202`
 *
 * WHY THE VENEER ADDRESSES ARE LOAD-BEARING
 * The app has NO vector table. It runs on the bootloader's (VTOR = 0x08000000,
 * MSP = 0x20000600). That table lives in write-protected flash and branches
 * straight to these addresses, so a veneer SLOT may never move; only its `bl`
 * target may change.
 *
 * THE SLOT MAP IS NOT LINEAR  (corrects docs/hiworld-startup-sequence.md §2)
 * The quoted rule `veneer(IRQn) = 0x08002072 + 8*IRQn` holds only for IRQ0..10
 * and IRQ23..41. The reason is now clear: the app's veneer array is laid out in
 * *STM32F103* vector order (this firmware is an F103 port), while the chip is a
 * Nations N32L406 with different interrupt numbers. The bootloader's table is
 * what bridges the two, e.g. for the CAN block:
 *
 *     N32 CAN_TX  = IRQ53 -> slot 28   (F103 CAN1_TX  = IRQ19)
 *     N32 CAN_RX0 = IRQ54 -> slot 29   (F103 CAN1_RX0 = IRQ20)
 *     N32 CAN_RX1 = IRQ55 -> slot 30   (F103 CAN1_RX1 = IRQ21)
 *     N32 CAN_SCE = IRQ56 -> slot 31   (F103 CAN1_SCE = IRQ22)
 *     N32 ADC     = IRQ19 -> slot 27   (F103 ADC1_2   = IRQ18)
 *
 * Consequence: `can_init`'s NVIC_Init(IRQn = 0x36 = 54) is CORRECT, and the
 * "CAN RX0 anomaly" in the docs does not exist. CAN_RX0_IRQn really is 54 on
 * this part (confirmed in the vendor header), and the bootloader routes IRQ54
 * to slot 29 -- exactly where the stock CAN RX handler sits. Do not "fix" it.
 *
 * Slots the bootloader never dispatches to are unreachable by hardware and are
 * kept only as padding so the reachable slots stay at their addresses.
 *
 * Handlers are .weak: porting a subsystem overrides the default, which
 * otherwise reproduces the stock fatal_error_reset(<original code>).
 * ==========================================================================*/

    .syntax unified
    .cpu    cortex-m4
    .thumb

    .section .image_entry, "ax", %progbits
    .align  1

/* ---- 0x08002000: 42 bytes, unreachable --------------------------------------
 * Stock has ARM C-library __rt_stackheap_init fragments here, reached only from
 * its own __main. Nothing branches here from outside, so fill with `b .` to
 * park a stray branch instead of letting it run on into the veneer array. */
_preamble_filler:
    .rept   21
    b       .
    .endr
    .org    0x2a, 0x00          /* veneer array must start at 0x0800202a */

/* ---- 0x0800202a: the 59 veneers ------------------------------------------ */
    .macro  VENEER  handler
    push    {r4, lr}
    bl      ''' + B + '''handler
    pop     {r4, pc}
    .endm

''')

for s in range(59):
    a = 0x0800202a + 8 * s
    src = slot_src.get(s, '--')
    if s in real:
        what = 'STOCK HANDLER @0x%08x' % real[s]
    elif s in empty:
        what = 'stock: empty stub (bx lr)'
    else:
        what = 'stock: fatal_error_reset(%d)' % trap[s]
    A('    /* slot %-2d 0x%08x  %-14s %s */\n' % (s, a, src, what))
    A('    VENEER  %s\n' % sym(s))

A('''
    .org    0x202, 0x00         /* HARD REQUIREMENT: entry veneer at 0x08002202 */

/* ---- 0x08002202: app entry ------------------------------------------------
 * The bootloader does `bl 0x08002202` once *0x08001800 == 0x19780217.
 * Stock calls the ARM C-lib __main (scatterload -> __rt_entry -> main). We call
 * our GCC-native equivalent in startup.c, which does the same job. */
    .global image_entry
    .type   image_entry, %function
image_entry:
    push    {r4, lr}
    bl      _start_c
    pop     {r4, pc}
    .size   image_entry, . - image_entry

    .org    0x20a, 0x00
_image_preamble_end:

/* ==========================================================================
 * Default handlers. These live in .text, NOT in the fixed preamble, so they
 * may be placed anywhere. Each reproduces the stock behaviour.
 * ========================================================================*/
    .section .text.default_handlers, "ax", %progbits
    .align  1

    .macro  TRAP_HANDLER name, code
    .weak   ''' + B + '''name
    .type   ''' + B + '''name, %function
''' + B + '''name:
    movs    r0, #''' + B + '''code
    b       fatal_error_reset
    .size   ''' + B + '''name, . - ''' + B + '''name
    .endm

    .macro  EMPTY_HANDLER name
    .weak   ''' + B + '''name
    .type   ''' + B + '''name, %function
''' + B + '''name:
    bx      lr
    .size   ''' + B + '''name, . - ''' + B + '''name
    .endm

''')

for s in range(59):
    if s in real:
        continue
    if s in empty:
        A('    EMPTY_HANDLER %s\n' % sym(s))
    else:
        A('    TRAP_HANDLER  %s, %d\n' % (sym(s), trap[s]))

A('''
/* The five slots that carry a real handler in the stock image. Weak defaults so
 * the image links before those subsystems are ported; each is overridden by the
 * C definition of the same name once its subsystem lands.
 *   trap codes here are NOT stock (stock has real code at these slots) -- they
 *   are distinct 2xx values so an unported handler firing is identifiable. */
''')
for s in sorted(real):
    A('    TRAP_HANDLER  %-22s %d   /* stock @0x%08x */\n' % (sym(s) + ',', 200 + s, real[s]))

A('\n    .end\n')

open('app/startup/crt0.S', 'w', newline='\n', encoding='utf-8').write(''.join(L))
print('wrote app/startup/crt0.S')
print('real handler slots:', {s: sym(s) for s in sorted(real)})
print('empty slots       :', {s: sym(s) for s in sorted(empty)})
print('unreachable slots :', [s for s in range(59) if s not in slot_src])
